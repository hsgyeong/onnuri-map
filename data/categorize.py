def classify(items: str):
    text = (items or "").replace(",", " ")
    for major, sub, keywords in RULES:
        for kw in keywords:
            if kw in text:
                return major, sub
    return "기타", "기타"


def main():
    stores = json.loads(STORES.read_text(encoding="utf-8"))
    maj = collections.Counter()
    sub = collections.Counter()
    for s in stores:
        m, sb = classify(s.get("items"))
        s["category"] = m
        s["subcategory"] = sb
        maj[m] += 1
        sub[(m, sb)] += 1

    STORES.write_text(json.dumps(stores, ensure_ascii=False), encoding="utf-8")

    total = len(stores)
    print(f"총 {total:,}개 분류 완료\n")
    print("=== 대분류 분포 ===")
    for m, c in maj.most_common():
        print(f"  {c:>7,} ({c*100/total:4.1f}%)  {m}")
    print(f"\n미분류(기타) 비율: {maj['기타']*100/total:.1f}%\n")
    print("=== 소분류 분포 ===")
    for (m, sb), c in sub.most_common():
        print(f"  {c:>7,}  {m} > {sb}")


if __name__ == "__main__":
    main()
