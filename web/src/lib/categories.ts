// 대분류 -> 소분류 목록 (RULES 순서 유지, 중복 제거)
export const SUBS_BY_MAJOR: Record<string, string[]> = (() => {
  const map: Record<string, string[]> = {};
  for (const r of RULES) {
    (map[r.major] ??= []);
    if (!map[r.major].includes(r.sub)) map[r.major].push(r.sub);
  }
  map["기타"] = ["기타"];
  return map;
})();

export function classify(items: string | null | undefined): { major: string; sub: string } {
  const text = (items || "").replace(/,/g, " ");
  for (const r of RULES) {
    for (const kw of r.kw) {
      if (text.includes(kw)) return { major: r.major, sub: r.sub };
    }
  }
  return { major: "기타", sub: "기타" };
}
